// TestDumpLevelShiftSynth writes the synthetic cases as upstream-style CSVs
// for the reference oracle. It only runs when LEVEL_SHIFT_DUMP_DIR is set.
func TestDumpLevelShiftSynth(t *testing.T) {
	dir := os.Getenv("LEVEL_SHIFT_DUMP_DIR")
	if dir == "" {
		t.Skip("LEVEL_SHIFT_DUMP_DIR not set")
	}
	for _, c := range synthOracleCases() {
		daily, hourly := c.spec.build()
		writeFixtureCSV(t, filepath.Join(dir, c.spec.name+"-1d.csv"), daily, true)
		writeFixtureCSV(t, filepath.Join(dir, c.spec.name+"-1h.csv"), hourly, false)
		now := fixtureNow(daily)
		if err := os.WriteFile(filepath.Join(dir, c.spec.name+".now"), []byte(now.UTC().Format(time.RFC3339)), 0o600); err != nil {
			t.Fatal(err)
		}
	}
}

func writeFixtureCSV(t *testing.T, path string, bars []models.Bar, daily bool) {
	t.Helper()
	f, err := os.Create(path)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = f.Close() }()
	w := csv.NewWriter(f)
	header := []string{"Date", "Open", "High", "Low", "Close", "Adj Close", "Volume"}
	if daily {
		header = append(header, "Dividends", "Stock Splits", "Repaired?")
	}
	_ = w.Write(header)
	ff := func(v float64) string { return strconv.FormatFloat(v, 'g', 17, 64) }
	for _, b := range bars {
		row := []string{b.Date.Format("2006-01-02 15:04:05-07:00"), ff(b.Open), ff(b.High), ff(b.Low), ff(b.Close), ff(b.AdjClose), strconv.FormatInt(b.Volume, 10)}
		if daily {
			row = append(row, ff(b.Dividends), ff(b.Splits), strconv.FormatBool(b.Repaired))
		}
		_ = w.Write(row)
	}
	w.Flush()
	if err := w.Error(); err != nil {
		t.Fatal(err)
	}
}

// TestRepairLevelShiftSynthOracle checks the Go port against upstream on the
// synthetic cases: fetch count, which rows are repaired, the multiplier,
// volume (inverse multiplier, half-even) and untouched dividends.
func TestRepairLevelShiftSynthOracle(t *testing.T) {
	for _, c := range synthOracleCases() {
		t.Run(c.spec.name, func(t *testing.T) {
			daily, hourlyBars := c.spec.build()
			hourly := &fakeHourly{bars: hourlyBars}
			got, err := New(levelShiftOptions("SYN", hourly, fixtureNow(daily))).repairLevelShifts(daily)
			if err != nil {
				t.Fatalf("repairLevelShifts: %v", err)
			}
			if len(hourly.calls) != c.fetches {
				t.Fatalf("fetches = %d, want %d", len(hourly.calls), c.fetches)
			}
			for i := range got {
				want, wantRepaired := daily[i], daily[i].Repaired
				if i < c.repaired {
					m := c.mult
					want.Open *= m
					want.High *= m
					want.Low *= m
					want.Close *= m
					want.AdjClose *= m
					want.Volume = int64(math.RoundToEven(float64(want.Volume) / m))
					wantRepaired = true
				}
				for _, p := range [][3]float64{{got[i].Open, want.Open}, {got[i].High, want.High}, {got[i].Low, want.Low}, {got[i].Close, want.Close}, {got[i].AdjClose, want.AdjClose}} {
					if !closeTo(p[0], p[1], 1e-12) {
						t.Fatalf("row %d price %v, want %v", i, p[0], p[1])
					}
				}
				if got[i].Volume != want.Volume {
					t.Fatalf("row %d volume %d, want %d", i, got[i].Volume, want.Volume)
				}
				if got[i].Repaired != wantRepaired {
					t.Fatalf("row %d Repaired=%v, want %v", i, got[i].Repaired, wantRepaired)
				}
				if got[i].Dividends != daily[i].Dividends {
					t.Fatalf("row %d dividends changed", i)
				}
			}
		})
	}
}
