// synthShift describes a synthetic daily series with a level shift, plus the
// 1h data Yahoo would serve for it. Rows before shiftRow have daily prices
// multiplied by badFactor and daily volume divided by it (Yahoo's error);
// genuineFactor instead moves the true price, so 1h data moves too.
type synthShift struct {
	name          string
	rows          int
	shiftRow      int
	badFactor     float64 // 1 = no bad shift
	shiftRow2     int     // rows before it are also multiplied by badFactor2
	badFactor2    float64
	genuineFactor float64 // 1 = no genuine move
	flatVolume    bool    // volume does not move with the bad shift
	splitRow      int     // >= 0 puts a split on this row
	dividendRow   int     // >= 0 puts a dividend on this row
	hourlyFrom    int     // first row with 1h data
	hourlySkew    map[int]float64
	repairedRows  int // rows (oldest first) already flagged Repaired
	end           time.Time
}

func (s synthShift) withDefaults() synthShift {
	if s.rows == 0 {
		s.rows = 30
	}
	if s.shiftRow == 0 {
		s.shiftRow = 18
	}
	if s.badFactor == 0 {
		s.badFactor = 1
	}
	if s.badFactor2 == 0 {
		s.badFactor2 = 1
	}
	if s.genuineFactor == 0 {
		s.genuineFactor = 1
	}
	if s.end.IsZero() {
		s.end = time.Date(2026, 10, 30, 0, 0, 0, 0, nyLocation())
	}
	return s
}

func nyLocation() *time.Location {
	loc, err := time.LoadLocation("America/New_York")
	if err != nil {
		panic(err)
	}
	return loc
}

// tradingDays returns n weekdays ending on end, oldest first, at midnight.
func tradingDays(end time.Time, n int) []time.Time {
	days := make([]time.Time, 0, n)
	for d := end; len(days) < n; d = d.AddDate(0, 0, -1) {
		if d.Weekday() != time.Saturday && d.Weekday() != time.Sunday {
			days = append(days, d)
		}
	}
	for i, j := 0, len(days)-1; i < j; i, j = i+1, j-1 {
		days[i], days[j] = days[j], days[i]
	}
	return days
}

// build returns the (bad) daily bars and the 1h bars.
func (s synthShift) build() (daily, hourly []models.Bar) {
	s = s.withDefaults()
	days := tradingDays(s.end, s.rows)
	for i, day := range days {
		base := 40 * (1 + 0.03*math.Sin(float64(i)*1.7))
		if i < s.shiftRow {
			base *= s.genuineFactor
		}
		vol := 1e6 * (1 + 0.2*math.Cos(float64(i)*2.3))
		var dayBar models.Bar
		for h := 0; h < 7; h++ {
			o := base * (1 + 0.004*math.Sin(float64(i*7+h)))
			c := base * (1 + 0.004*math.Sin(float64(i*7+h+1)))
			hb := models.Bar{
				Date:   time.Date(day.Year(), day.Month(), day.Day(), 9+h, 30, 0, 0, day.Location()),
				Open:   o,
				High:   math.Max(o, c) * 1.002,
				Low:    math.Min(o, c) * 0.998,
				Close:  c,
				Volume: int64(vol / 7),
			}
			hb.AdjClose = hb.Close
			if skew, ok := s.hourlySkew[i]; ok {
				hb.Open *= skew
				hb.High *= skew
				hb.Low *= skew
				hb.Close *= skew
			}
			if i >= s.hourlyFrom {
				hourly = append(hourly, hb)
			}
			if h == 0 {
				dayBar = models.Bar{Open: o, High: hb.High, Low: hb.Low}
			}
			dayBar.High = math.Max(dayBar.High, math.Max(o, c)*1.002)
			dayBar.Low = math.Min(dayBar.Low, math.Min(o, c)*0.998)
			dayBar.Close = c
		}
		dayBar.Date = day
		dayBar.AdjClose = dayBar.Close
		dayBar.Volume = int64(vol)
		f := 1.0
		if i < s.shiftRow {
			f *= s.badFactor
		}
		if i < s.shiftRow2 {
			f *= s.badFactor2
		}
		if f != 1 {
			dayBar.Open *= f
			dayBar.High *= f
			dayBar.Low *= f
			dayBar.Close *= f
			dayBar.AdjClose *= f
			if !s.flatVolume {
				dayBar.Volume = int64(math.Round(float64(dayBar.Volume) / f))
			}
		}
		if i == s.splitRow && s.splitRow > 0 {
			dayBar.Splits = 2
		}
		if i == s.dividendRow && s.dividendRow > 0 {
			dayBar.Dividends = 0.25
		}
		dayBar.Repaired = i < s.repairedRows
		daily = append(daily, dayBar)
	}
	return daily, hourly
}

// synthOracleCase is a synthetic case with its expected result, generated by
// running Python yfinance 1.8.0 (e2f6104)
// PriceHistory._fix_unexplained_level_shifts on the same rows: the CSVs
// written by TestDumpLevelShiftSynth, with history() patched to serve the 1h
// CSV within the requested window (as upstream's test does) and
// pd.Timestamp.now patched to one week after the last row.
type synthOracleCase struct {
	spec    synthShift
	fetches int
	// repaired is the number of rows (oldest first) repaired; mult is the
	// factor applied to their prices.
	repaired int
	mult     float64
}

